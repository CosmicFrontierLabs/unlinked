#!/usr/bin/env python3
"""Check parameter help, filtering and accessible validation without saving edits."""
import argparse
import re
from playwright.sync_api import sync_playwright, expect
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url',required=True)
parser.add_argument('--model',required=True)
parser.add_argument('--browser')
parser.add_argument('--engine', choices=['chromium', 'firefox', 'webkit'], default='chromium')
args=parser.parse_args()
with sync_playwright() as p:
    browser=getattr(p, args.engine).launch(headless=True,**({'executable_path':args.browser} if args.browser else {}))
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.request.get(args.url+'/api/auth/dev-login')
    page.goto(args.url+args.model)
    diagram=page.get_by_role('region',name='Diagram',exact=True)
    expect(diagram.locator('.diagram svg').first).to_be_visible()
    diagram.locator('.diagram g.block').first.click()
    help_button=page.get_by_role('button',name='Help for Step time',exact=True)
    help_button.click()
    expect(help_button).to_have_attribute('aria-expanded','true')
    expect(page.locator('#'+help_button.get_attribute('aria-controls'))).to_be_visible()
    step=page.get_by_label('Step time (s)',exact=True)
    ids=step.get_attribute('aria-describedby').split()
    assert all(page.locator('#'+x).count()==1 for x in ids)
    help_button.press('Escape')
    expect(help_button).to_have_attribute('aria-expanded','false')
    diagram.get_by_role('button',name='Settings',exact=True).click()
    settings=page.get_by_role('region',name='Stored model settings')
    stop=settings.get_by_label('Stop time',exact=True)
    original=stop.input_value()
    stop.fill('-1');stop.blur()
    expect(stop).to_have_attribute('aria-invalid','true')
    expect(page.locator('#'+stop.get_attribute('aria-describedby'))).not_to_be_empty()
    stop.fill(original);stop.blur()
    expect(stop).not_to_have_attribute('aria-invalid','true')
    solver=settings.get_by_label('Solver',exact=True)
    original_solver=solver.input_value()
    solver.select_option('ode1' if original_solver != 'ode1' else 'ode4')
    diagram.locator('.diagram').focus();page.keyboard.press('Control+z')
    expect(solver).to_have_value(original_solver)
    # Integrator has enough parameters to offer filtering; adding stays unsaved.
    diagram.get_by_role('listitem',name=re.compile(r'^Integrator \(Integrator\):')).dblclick()
    source=page.get_by_label('Initial condition source',exact=True)
    expect(source).to_have_value('internal')
    source.select_option('external')
    expect(page.get_by_label('Initial condition',exact=True)).to_have_count(0)
    diagram.locator('.diagram').focus();page.keyboard.press('Control+z')
    expect(source).to_have_value('internal')
    expect(page.get_by_label('Initial condition',exact=True)).to_be_visible()
    page.keyboard.press('Control+Shift+z')
    expect(source).to_have_value('external')
    page.keyboard.press('Control+z')
    expect(source).to_have_value('internal')
    page.get_by_role('checkbox',name='Limit output',exact=True).click()
    expect(page.get_by_role('checkbox',name='Limit output',exact=True)).to_be_checked()
    search=page.get_by_role('searchbox',name='Search parameters',exact=True)
    expect(search).to_be_visible()
    search.fill('initial')
    expect(page.locator('.parameter-dialog')).to_contain_text('Initial condition')
    search.fill('zzzznomatch')
    expect(page.get_by_text('No matching parameters.',exact=True)).to_be_visible()
    search.fill('')
    expect(page.get_by_label('Initial condition',exact=True)).to_be_visible()
    page.screenshot(path='/tmp/unlinked-parameter-help.png')
    diagram.get_by_role('listitem',name=re.compile(r'^Ground \(Ground\):')).dblclick()
    expect(page.get_by_text('No matching parameters.',exact=True)).to_have_count(0)
    # Removing a wired reset port is rejected; the select must stay committed.
    guarded=browser.new_page(viewport={'width':1440,'height':1000})
    guarded.request.get(args.url+'/api/auth/dev-login')
    guarded.on('pageerror',lambda e:errors.append(str(e)))
    fixture='Model {\n Name "connected_reset"\n System {\n  Name "connected_reset"\n  Block {\n   BlockType Constant\n   Name "Reset"\n   SID "1"\n   Position [20, 40, 50, 70]\n   Value "1"\n  }\n  Block {\n   BlockType Integrator\n   Name "State"\n   SID "2"\n   Position [180, 40, 220, 80]\n   Ports [2, 1]\n   ExternalReset "rising"\n  }\n  Line {\n   SrcBlock "Reset"\n   SrcPort 1\n   DstBlock "State"\n   DstPort 2\n  }\n }\n}\n'
    guarded.route('**/api/projects/**/files/**/content',lambda route:route.fulfill(content_type='application/octet-stream',body=fixture))
    guarded.goto(args.url+args.model)
    guarded.locator('g.block[data-name="State"]').click()
    reset=guarded.get_by_label('External reset',exact=True)
    expect(reset).to_have_value('rising')
    reset.select_option('none')
    expect(guarded.locator('.edit-bar.error')).to_be_visible()
    expect(reset).to_have_value('rising')
    expect(guarded.locator('circle.port-hit[data-sid="2"][data-kind="in"][data-index="2"]')).to_have_count(1)
    guarded.close()
    assert not errors,errors
    print('PASS: keyboard/touch help controls, description IDs, solver validation and recovery, parameter filtering')
    browser.close()

    fn defaults_prefer_outports_then_block_outputs() {
        let outports = vec!["cart position (m)".to_string()];
        assert_eq!(default_plotted(&signals(), &outports), vec![3]);
        assert_eq!(default_plotted(&signals(), &[]), vec![0, 2, 3]);
    }

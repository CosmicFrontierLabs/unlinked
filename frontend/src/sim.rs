/// Signals plotted by default when a data set loads.
const DEFAULT_PLOTTED: usize = 6;
/// Minimum time between plot refreshes while samples stream in.
const REFRESH_MS: f64 = 120.0;

#[derive(Properties, PartialEq)]
pub struct SimProps {
    /// Whether the simulation workspace is visible. Streaming survives tab changes.
    #[prop_or(true)]
    pub active: bool,
    #[prop_or_default]
    pub on_running_change: Callback<bool>,
    /// Project holding the model; its `.m` files are offered as init scripts.
    pub project_id: Uuid,
    pub file_id: Uuid,
    /// Version number to simulate (pinned by the server).
    pub version: i32,
    pub config: SimConfig,
    /// Original root Inport IDs and display names.
    pub inputs: Vec<(String, String)>,
    #[prop_or_default]
    pub has_random_sources: bool,
    /// Names of the model's root Outport blocks, plotted by default.
    pub outports: Vec<String>,
}

/// Signal label without the leading model name.
fn label(name: &str) -> &str {
    name.split_once('/').map_or(name, |(_, rest)| rest)
}

/// Whether a signal was generated by lowering (matrix-gain terms, transfer
/// function states, ...) rather than being a block's own output. Lowering
/// marks every generated ID with `$`.
fn is_generated(signal: &SimulationSignal) -> bool {
    signal.id.contains('$')
}

fn is_outport(signal: &SimulationSignal, outports: &[String]) -> bool {
    let l = label(&signal.name);
    outports.iter().any(|o| {
        l.strip_prefix(o.as_str())
            .is_some_and(|r| r.starts_with(':'))
    })
}

/// Signals to plot for a new data set: the root Outports when any are
/// present, otherwise the first few block outputs.
fn default_plotted(signals: &[SimulationSignal], outports: &[String]) -> Vec<usize> {
    let outs: Vec<usize> = signals
        .iter()
        .enumerate()
        .filter(|(_, s)| is_outport(s, outports))
        .map(|(i, _)| i)
        .take(DEFAULT_PLOTTED)
        .collect();
    if outs.is_empty() {
        signals
            .iter()
            .enumerate()
            .filter(|(_, s)| !is_generated(s))
            .map(|(i, _)| i)
            .take(DEFAULT_PLOTTED)
            .collect()
    } else {
        outs
    }
}

/// Columns of a stored trace in the order and with the names recorded when
/// it ran. Signals are matched to trace columns by stable ID; trace columns
/// without recorded metadata (runs stored before names were kept) follow,
/// labelled by ID.
fn stored_columns(
    mut columns: BTreeMap<String, Vec<f64>>,
    recorded: &[SimulationSignal],
) -> (Vec<SimulationSignal>, Vec<Vec<f64>>) {
    let mut signals = Vec::with_capacity(columns.len());
    let mut data = Vec::with_capacity(columns.len());
    for s in recorded {
        if let Some(column) = columns.remove(&s.id) {
            signals.push(s.clone());
            data.push(column);
        }
    }
    for (id, column) in columns {
        signals.push(SimulationSignal {
            name: id.clone(),
            id,
        });
        data.push(column);
    }
    (signals, data)
}

/// Picker order: Outports, then other block outputs, then generated
/// signals (listed only when `show_generated`). Indices stay the trace
/// order, so selection is unaffected by presentation.
fn picker_order(
    signals: &[SimulationSignal],
    outports: &[String],
    show_generated: bool,
) -> Vec<usize> {
    let rank = |s: &SimulationSignal| {
        if is_outport(s, outports) {
            0
        } else if !is_generated(s) {
            1
        } else {
            2
        }
    };
    let mut order: Vec<usize> = (0..signals.len())
        .filter(|&i| show_generated || !is_generated(&signals[i]))
        .collect();
    order.sort_by_key(|&i| rank(&signals[i]));
    order
}

#[derive(Clone, PartialEq)]
enum RunState {
    Idle,
    Connecting,
    Loading,
    Running(Option<Uuid>),
    Stopping,
    Finished(SimulationStatus, Option<String>),
    Error(String),
}

impl RunState {
    fn active(&self) -> bool {
        matches!(
            self,
            RunState::Connecting | RunState::Running(_) | RunState::Stopping
        )
    }
}

/// Mutable state shared between the component and its async tasks.
#[derive(Default)]
struct Controller {
    /// Identifies the current data set; bumped on every run/load and on unmount.
    generation: u64,
    signals: Vec<SimulationSignal>,
    plotted: Vec<usize>,
    time: Vec<f64>,
    columns: Vec<Vec<f64>>,
    session: Option<PlotSession>,
    sender: Option<Sender<SimulationSocket>>,
    /// Server id of the live run, once known.
    run_id: Option<Uuid>,
    run_version: Option<i32>,
    stopping: bool,
    /// Aborts the live run's socket task, dropping its receiver at once.
    task: Option<AbortHandle>,
    last_refresh: f64,
    requested_options: Option<SimulationOptions>,
}

impl Controller {
    /// Start a new data set, invalidating every task of the previous one.
    fn reset(&mut self) -> u64 {
        self.generation += 1;
        if let Some(task) = self.task.take() {
            task.abort();
        }
        self.signals.clear();
        self.plotted.clear();
        self.time.clear();
        self.columns.clear();
        self.session = None;
        self.sender = None;
        self.run_id = None;
        self.run_version = None;
        self.stopping = false;
        self.requested_options = None;
        self.last_refresh = 0.0;
        self.generation
    }

    fn refresh_plot(&self) {
        if let Some(session) = &self.session {
            for (line, &i) in self.plotted.iter().enumerate() {
                if let Some(y) = self.columns.get(i) {
                    let n = y.len().min(self.time.len());
                    let _ = session.set_line_data(0, line, &self.time[..n], &y[..n]);
                }
            }
        }
    }

    /// Build a figure with one line per plotted signal and bind it to the canvas.
    fn bind_plot(&mut self, canvas_id: &str, width_px: f64) -> Result<(), String> {
        self.session = None;
        if self.signals.is_empty() {
            return Ok(());
        }
        let err = |e: wasm_bindgen::JsValue| e.as_string().unwrap_or_else(|| "plot error".into());
        // Standard axes with data ticks: simulation results need readable
        // time and value scales, not scope-style corner readouts.
        let mut fig = WasmFigure::new((width_px / 100.0).max(4.0), 3.6);
        let ax = fig.add_subplot(1, 1, 1).map_err(err)?;
        fig.set_xlabel(ax, "time (s)").map_err(err)?;
        for &i in &self.plotted {
            let y = self.columns.get(i).map(Vec::as_slice).unwrap_or(&[]);
            let n = y.len().min(self.time.len());
            let style = js_sys::Object::new();
            js_sys::Reflect::set(&style, &"color".into(), &inspector::color(i).into())
                .map_err(err)?;
            fig.plot_styled(ax, &self.time[..n], &y[..n], &style)
                .map_err(err)?;
        }
        if !self.plotted.is_empty() {
            let labels = self
                .plotted
                .iter()
                .map(|&i| label(&self.signals[i].name).to_string())
                .collect();
            fig.legend(ax, labels).map_err(err)?;
        }
        self.session = Some(plot::bind(fig, canvas_id).map_err(err)?);
        Ok(())
    }

    fn csv(&self) -> String {
        let mut out = String::from("time");
        for s in &self.signals {
            out.push(',');
            out.push_str(&csv_field(&s.name));
        }
        out.push('\n');
        for (row, t) in self.time.iter().enumerate() {
            out.push_str(&t.to_string());
            for col in &self.columns {
                out.push(',');
                if let Some(v) = col.get(row) {
                    out.push_str(&v.to_string());
                }
            }
            out.push('\n');
        }
        out
    }
}

/// RFC 4180 field: quoted when it contains a delimiter, quote or newline.
fn csv_field(s: &str) -> String {
    if s.contains([',', '"', '\n', '\r']) {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

/// The simulator solver matching the model's, if it implements that one.
fn model_solver(config: &SimConfig) -> Option<Solver> {
    let descriptor = config.solver.as_deref().and_then(solver_descriptor)?;
    match descriptor.simulation_solver? {
        "euler" => Some(Solver::Euler),
        "rk4" => Some(Solver::Rk4),
        "rk45" => Some(Solver::Rk45),
        _ => None,
    }
}

/// Initial run options from the model's solver settings, and a note for
/// each option that does not come from them: settings the model lacks or
/// does not give as plain numbers, invalid ones, and solvers the simulator
/// does not implement.
pub(crate) fn initial_options(config: &SimConfig) -> (SimulationOptions, Vec<String>) {
    let mut notes = Vec::new();
    let mut o = SimulationOptions::default();
    let number = |v: Option<&String>| {
        v.and_then(|v| v.trim().parse::<f64>().ok())
            .filter(|v| v.is_finite())
    };
    let shown = |v: Option<&String>| v.map_or("unset".to_string(), |v| format!("\"{}\"", v.trim()));
    let mut take =
        |label: &str, stored: Option<&String>, valid: &dyn Fn(f64) -> bool, fallback: f64| {
            match number(stored).filter(|v| valid(*v)) {
                Some(v) => v,
                None => {
                    notes.push(format!(
                        "{label}: the model's {} → {}.",
                        shown(stored),
                        fmt_num(fallback)
                    ));
                    fallback
                }
            }
        };
    o.start = take("Start", config.start_time.as_ref(), &|_| true, 0.0);
    let start = o.start;
    o.stop = take(
        "Stop",
        config.stop_time.as_ref(),
        &|v| v >= start,
        start + 10.0,
    );
    o.solver = model_solver(config).unwrap_or(Solver::Rk45);
    let span = o.stop - o.start;
    let default_step = if span == 0.0 { 0.01 } else { span / 1000.0 };
    match o.solver {
        Solver::Euler | Solver::Rk4 => {
            o.step = take(
                "Output step",
                config.fixed_step.as_ref(),
                &|v| v > 0.0,
                default_step,
            );
        }
        Solver::Rk45 => {
            o.step = default_step;
            o.relative_tolerance = take(
                "Rel tol",
                config.raw.get("RelTol"),
                &|v| v > 0.0 && v <= 1.0,
                o.relative_tolerance,
            );
            o.absolute_tolerance = take(
                "Abs tol",
                config.raw.get("AbsTol"),
                &|v| v > 0.0,
                o.absolute_tolerance,
            );
        }
    }
    if model_solver(config).is_none() {
        notes.insert(
            0,
            match &config.solver {
                Some(s) => {
                    format!("Solver: the simulator does not implement the model's {s} → rk45.")
                }
                None => "Solver: the model stores none → rk45.".to_string(),
            },
        );
    }
    (o, notes)
}

pub(crate) fn solver_name(s: Solver) -> &'static str {
    match s {
        Solver::Euler => "euler",
        Solver::Rk4 => "rk4",
        Solver::Rk45 => "rk45",
    }
}

/// Parse `NAME = EXPR` lines; blank lines and `%` comments are skipped.
fn parse_workspace(text: &str) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    for (i, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('%') {
            continue;
        }
        let (name, expr) = line
            .split_once('=')
            .ok_or_else(|| format!("line {}: expected NAME = EXPR", i + 1))?;
        out.insert(
            name.trim().to_string(),
            expr.trim().trim_end_matches(';').to_string(),
        );
    }
    Ok(out)
}

/// Stream one run's messages into the controller until it finishes, fails,
/// or the data set is superseded.
async fn stream(
    ctl: Rc<RefCell<Controller>>,
    generation: u64,
    mut rx: ws_bridge::yew_client::Receiver<SimulationSocket>,
    state: UseStateHandle<RunState>,
    rebind: UseReducerHandle<Reload>,
    outports: Vec<String>,
    progress: UseForceUpdateHandle,
) {
    let current = |ctl: &Rc<RefCell<Controller>>| ctl.borrow().generation == generation;
    let mut terminal = false;
    while let Some(msg) = rx.recv().await {
        if !current(&ctl) {
            return;
        }
        match msg {
            Ok(SimulationServerMsg::SimulationStatus { run }) => match run.status {
                SimulationStatus::Running => {
                    ctl.borrow_mut().run_id = Some(run.id);
                    if !ctl.borrow().stopping {
                        state.set(RunState::Running(Some(run.id)));
                    }
                }
                done => {
                    ctl.borrow().refresh_plot();
                    state.set(RunState::Finished(done, run.error));
                    terminal = true;
                    break;
                }
            },
            Ok(SimulationServerMsg::SimulationStarted { run_id, signals }) => {
                {
                    let mut c = ctl.borrow_mut();
                    c.columns = vec![Vec::new(); signals.len()];
                    c.plotted = default_plotted(&signals, &outports);
                    c.signals = signals;
                    c.run_id = Some(run_id);
                }
                rebind.dispatch(());
                if !ctl.borrow().stopping {
                    state.set(RunState::Running(Some(run_id)));
                }
            }
            Ok(SimulationServerMsg::SimulationSamples { time, values, .. }) => {
                let mut c = ctl.borrow_mut();
                c.time.extend_from_slice(&time);
                for row in &values {
                    for (col, v) in c.columns.iter_mut().zip(row) {
                        col.push(*v);
                    }
                }
                let now = js_sys::Date::now();
                if now - c.last_refresh > REFRESH_MS {
                    c.last_refresh = now;
                    c.refresh_plot();
                    progress.force_update();
                }
            }
            Ok(SimulationServerMsg::Error { message }) => {
                state.set(RunState::Error(message));
                terminal = true;
                break;
            }
            Ok(SimulationServerMsg::Heartbeat) => {}
            Err(e) => {
                state.set(RunState::Error(format!("connection error: {e}")));
                terminal = true;
                break;
            }
        }
    }
    if current(&ctl) {
        ctl.borrow_mut().sender = None;
        if !terminal {
            state.set(RunState::Error(
                "connection closed before the run finished".into(),
            ));
        }
    }
}

#[function_component(SimulationPanel)]
pub fn simulation_panel(props: &SimProps) -> Html {
    let options = use_state(|| RunForm::from(initial_options(&props.config).0));
    let differences = initial_options(&props.config).1;
    let workspace = use_state(String::new);
    let inputs = use_state(BTreeMap::<String, String>::new);
    let state = use_state(|| RunState::Idle);
    let ctl = use_mut_ref(Controller::default);
    let progress = use_force_update();
    // Bumped whenever the plot must be rebuilt (new data set or selection).
    let rebind = use_reload();
    // Presentation only: generated signals stay in the trace and plot.
    let show_generated = use_state(|| false);
    let signal_query = use_state(String::new);
    let current_version_only = use_state(|| false);
    let toggle_generated = {
        let show_generated = show_generated.clone();
        Callback::from(move |_: Event| show_generated.set(!*show_generated))
    };
    let plot_host = use_node_ref();
    let reload = use_reload();
    let runs = use_fetch((props.file_id, reload.0), |(f, _)| api::simulation_runs(f));
    let scripts = use_fetch(props.project_id, |p| async move {
        let files = api::files(p).await?;
        Ok(files
            .into_iter()
            .filter(|f| f.path.to_ascii_lowercase().ends_with(".m"))
            .collect::<Vec<FileInfo>>())
    });
    // Selected init script as (file, pinned version number).
    let init_script = use_state(|| None::<(Uuid, i32)>);
    let canvas_id = format!("sim-plot-{}", props.file_id);

    let needs_rebind = use_mut_ref(|| true);
    {
        let needs_rebind = needs_rebind.clone();
        use_effect_with(rebind.0, move |_| *needs_rebind.borrow_mut() = true);
    }
    {
        let (ctl, plot_host, canvas_id) = (ctl.clone(), plot_host.clone(), canvas_id.clone());
        use_effect_with((rebind.0, props.active), move |(_, active)| {
            if !active || !*needs_rebind.borrow() {
                return;
            }
            let width = plot_host
                .cast::<web_sys::HtmlElement>()
                .map(|e| e.client_width() as f64)
                .unwrap_or(800.0);
            if let Err(e) = ctl.borrow_mut().bind_plot(&canvas_id, width) {
                web_sys::console::error_1(&e.into());
            } else {
                *needs_rebind.borrow_mut() = false;
            }
        });
    }

    // On unmount: supersede any running stream and ask the server to cancel.
    {
        let ctl = ctl.clone();
        use_effect_with((), move |_| {
            move || {
                let (sender, run_id) = {
                    let mut c = ctl.borrow_mut();
                    let live = (c.sender.take(), c.run_id.take());
                    c.reset();
                    live
                };
                // Aborting the task dropped the receiver; ask the server to
                // cancel, then drop the sender so the socket closes.
                if let (Some(mut tx), Some(run_id)) = (sender, run_id) {
                    spawn_local(async move {
                        let _ = tx
                            .send(SimulationClientMsg::CancelSimulation { run_id })
                            .await;
                    });
                }
            }
        });
    }

    let run = {
        let (options, workspace, state, ctl, rebind, reload) = (
            options.clone(),
            workspace.clone(),
            state.clone(),
            ctl.clone(),
            rebind.clone(),
            reload.clone(),
        );
        let (file_id, version) = (props.file_id, props.version);
        let outports = props.outports.clone();
        let input_ports = props.inputs.clone();
        let inputs = inputs.clone();
        let init_script = init_script.clone();
        let progress = progress.clone();
        Callback::from(move |_: MouseEvent| {
            if state.active() {
                return;
            }
            let Ok((validated, _)) = options.validate() else {
                return;
            };
            let init_script = *init_script;
            let ws_vars = match parse_workspace(&workspace) {
                Ok(v) => v,
                Err(e) => {
                    state.set(RunState::Error(e));
                    return;
                }
            };
            if let Some((_, name)) = input_ports
                .iter()
                .find(|(id, _)| inputs.get(id).is_none_or(|v| v.trim().is_empty()))
            {
                state.set(RunState::Error(format!(
                    "Enter an explicit constant value for root input {name}."
                )));
                return;
            }
            let request = SimulationRequest {
                options: validated,
                workspace: ws_vars,
                inputs: (*inputs).clone(),
                version: Some(version),
                init_script: init_script.map(|(file_id, version)| SimulationInitScript {
                    file_id,
                    version: Some(version),
                }),
            };
            let conn = match ws_bridge::yew_client::connect::<SimulationSocket>() {
                Ok(c) => c,
                Err(e) => {
                    state.set(RunState::Error(format!("cannot connect: {e}")));
                    return;
                }
            };
            let generation = ctl.borrow_mut().reset();
            ctl.borrow_mut().run_version = Some(version);
            ctl.borrow_mut().requested_options = Some(request.options.clone());
            rebind.dispatch(());
            state.set(RunState::Connecting);
            let (mut tx, rx) = conn.split();
            let (state, ctl, rebind, reload, outports) = (
                state.clone(),
                ctl.clone(),
                rebind.clone(),
                reload.clone(),
                outports.clone(),
            );
            let (abort, registration) = AbortHandle::new_pair();
            ctl.borrow_mut().task = Some(abort);
            let progress = progress.clone();
            let task = async move {
                if let Err(e) = tx
                    .send(SimulationClientMsg::Simulate { file_id, request })
                    .await
                {
                    state.set(RunState::Error(format!("send failed: {e}")));
                    return;
                }
                if ctl.borrow().generation != generation {
                    return;
                }
                ctl.borrow_mut().sender = Some(tx);
                stream(ctl, generation, rx, state, rebind, outports, progress).await;
                reload.dispatch(());
            };
            spawn_local(async move {
                let _ = Abortable::new(task, registration).await;
            });
        })
    };

    let cancel = {
        let (ctl, state, rebind, reload) =
            (ctl.clone(), state.clone(), rebind.clone(), reload.clone());
        Callback::from(move |_: MouseEvent| {
            if !state.active() || matches!(&*state, RunState::Stopping) {
                return;
            }
            let run_id = ctl.borrow().run_id;
            let Some(run_id) = run_id else {
                // Dropping both socket halves cancels any server worker,
                // including one whose run ID has not reached us yet.
                ctl.borrow_mut().reset();
                state.set(RunState::Finished(SimulationStatus::Cancelled, None));
                rebind.dispatch(());
                reload.dispatch(());
                return;
            };
            ctl.borrow_mut().stopping = true;
            state.set(RunState::Stopping);
            let (ctl, state) = (ctl.clone(), state.clone());
            spawn_local(async move {
                let (tx, generation) = {
                    let mut c = ctl.borrow_mut();
                    (c.sender.take(), c.generation)
                };
                if let Some(mut tx) = tx {
                    let result = tx
                        .send(SimulationClientMsg::CancelSimulation { run_id })
                        .await;
                    let mut c = ctl.borrow_mut();
                    if c.generation == generation {
                        match result {
                            Ok(()) => c.sender = Some(tx),
                            Err(e) => {
                                if let Some(task) = c.task.take() {
                                    task.abort();
                                }
                                state.set(RunState::Error(format!(
                                    "Could not send Stop: {e}. The connection was closed."
                                )));
                            }
                        }
                    }
                }
            });
        })
    };

    let load_run = {
        let (state, ctl, rebind) = (state.clone(), ctl.clone(), rebind.clone());
        let outports = props.outports.clone();
        move |run: SimulationRun| {
            let (state, ctl, rebind, outports) =
                (state.clone(), ctl.clone(), rebind.clone(), outports.clone());
            Callback::from(move |_: MouseEvent| {
                if state.active() {
                    return;
                }
                let generation = ctl.borrow_mut().reset();
                state.set(RunState::Loading);
                rebind.dispatch(());
                let (state, ctl, rebind, outports) =
                    (state.clone(), ctl.clone(), rebind.clone(), outports.clone());
                let id = run.id;
                spawn_local(async move {
                    let result = api::simulation_result(id).await;
                    if ctl.borrow().generation != generation {
                        return;
                    }
                    match result {
                        Ok(result) => {
                            ctl.borrow_mut().requested_options =
                                Some(result.run.request.options.clone());
                            ctl.borrow_mut().run_id = Some(result.run.id);
                            ctl.borrow_mut().run_version = Some(result.run.file_version);
                            if let Some(trace) = result.trace {
                                let (signals, columns) =
                                    stored_columns(trace.signals, &result.signals);
                                let mut c = ctl.borrow_mut();
                                c.plotted = default_plotted(&signals, &outports);
                                c.signals = signals;
                                c.time = trace.time;
                                c.columns = columns;
                            }
                            rebind.dispatch(());
                            state.set(RunState::Finished(result.run.status, result.run.error));
                        }
                        Err(e) => state.set(RunState::Error(e.to_string())),
                    }
                });
            })
        }
    };

    let set_num = |field: fn(&mut RunForm) -> &mut String| {
        let options = options.clone();
        Callback::from(move |e: InputEvent| {
            let mut o = (*options).clone();
            *field(&mut o) = e.target_unchecked_into::<HtmlInputElement>().value();
            options.set(o);
        })
    };
    let reset_options = {
        let (options, config) = (options.clone(), props.config.clone());
        Callback::from(move |_: MouseEvent| options.set(RunForm::from(initial_options(&config).0)))
    };
    let set_solver = {
        let options = options.clone();
        Callback::from(move |e: Event| {
            let mut o = (*options).clone();
            o.solver = match e
                .target_unchecked_into::<HtmlSelectElement>()
                .value()
                .as_str()
            {
                "euler" => Solver::Euler,
                "rk4" => Solver::Rk4,
                _ => Solver::Rk45,
            };
            options.set(o);
        })
    };
    let set_init = {
        let (init_script, scripts) = (init_script.clone(), scripts.clone());
        Callback::from(move |e: Event| {
            let id = e.target_unchecked_into::<HtmlSelectElement>().value();
            let chosen = match &*scripts {
                Fetch::Ready(files) => files
                    .iter()
                    .find(|f| f.id.to_string() == id)
                    .map(|f| (f.id, f.latest.version)),
                _ => None,
            };
            init_script.set(chosen);
        })
    };
    let init_picker = view(&scripts, |files: &Vec<FileInfo>| {
        let selected = init_script.map(|(id, _)| id);
        html! {
            <select onchange={set_init.clone()} disabled={state.active()}>
                <option value="" selected={selected.is_none()}>{ "none" }</option>
                { for files.iter().map(|f| html! {
                    <option value={f.id.to_string()} selected={selected == Some(f.id)}>
                        { format!("{} (v{})", f.path, f.latest.version) }
                    </option>
                }) }
            </select>
        }
    });
    let set_workspace = {
        let workspace = workspace.clone();
        Callback::from(move |e: InputEvent| {
            workspace.set(e.target_unchecked_into::<HtmlTextAreaElement>().value())
        })
    };
    let toggle_signal = |i: usize| {
        let (ctl, rebind) = (ctl.clone(), rebind.clone());
        Callback::from(move |_: Event| {
            {
                let mut c = ctl.borrow_mut();
                if let Some(pos) = c.plotted.iter().position(|&x| x == i) {
                    c.plotted.remove(pos);
                } else {
                    c.plotted.push(i);
                    c.plotted.sort_unstable();
                }
            }
            rebind.dispatch(());
        })
    };

    let set_signal_query = {
        let query = signal_query.clone();
        Callback::from(move |e: InputEvent| {
            query.set(e.target_unchecked_into::<HtmlInputElement>().value())
        })
    };
    let toggle_version_filter = {
        let filter = current_version_only.clone();
        Callback::from(move |_: Event| filter.set(!*filter))
    };
    let signal_revision = {
        let c = ctl.borrow();
        (c.generation, c.signals.len())
    };
    let search_index = {
        let ctl = ctl.clone();
        use_memo(signal_revision, move |_| {
            ctl.borrow()
                .signals
                .iter()
                .map(|s| format!("{} {}", s.name.to_lowercase(), s.id.to_lowercase()))
                .collect::<Vec<_>>()
        })
    };
    let ordered_signals = {
        let ctl = ctl.clone();
        use_memo(
            (signal_revision, props.outports.clone(), *show_generated),
            move |(_, outports, generated)| {
                picker_order(&ctl.borrow().signals, outports, *generated)
            },
        )
    };
    let matching_signals = use_memo(
        (
            signal_query.trim().to_lowercase(),
            ordered_signals,
            search_index,
        ),
        |(query, order, index)| {
            if query.is_empty() {
                return (**order).clone();
            }
            order
                .iter()
                .copied()
                .filter(|&i| index[i].contains(query))
                .collect::<Vec<_>>()
        },
    );
    // Keep large traces usable without constructing thousands of controls.
    // Bulk actions apply to the rows shown; search exposes any other signal.
    let visible_signals: Vec<usize> = matching_signals.iter().take(200).copied().collect();
    let select_visible = |selected: bool| {
        let (ctl, rebind, visible) = (
            ctl.clone(),
            rebind.clone(),
            visible_signals.iter().copied().collect::<HashSet<_>>(),
        );
        Callback::from(move |_: MouseEvent| {
            let mut c = ctl.borrow_mut();
            if selected {
                c.plotted.extend(&visible);
                c.plotted.sort_unstable();
                c.plotted.dedup();
            } else {
                c.plotted.retain(|i| !visible.contains(i));
            }
            drop(c);
            rebind.dispatch(());
        })
    };

    let running = state.active();
    {
        let on_running_change = props.on_running_change.clone();
        use_effect_with(running, move |running| on_running_change.emit(*running));
    }
    let c = ctl.borrow();
    let samples = c.time.len();
    let plotted: HashSet<usize> = c.plotted.iter().copied().collect();
    let generated_count = c.signals.iter().filter(|s| is_generated(s)).count();
    let status = match &*state {
        RunState::Idle => html! { <span class="muted">{ "Ready" }</span> },
        RunState::Loading => html! { <span class="muted">{ "Loading run…" }</span> },
        RunState::Stopping => html! { <span class="running">{ "Stopping…" }</span> },
        RunState::Connecting => html! { <span class="muted">{ "Connecting…" }</span> },
        RunState::Running(_) => {
            html! { <span class="running">{ format!("Running… {samples} samples") }</span> }
        }
        RunState::Finished(SimulationStatus::Completed, _) => {
            html! { <span class="ok">{ format!("Completed · {samples} samples") }</span> }
        }
        RunState::Finished(SimulationStatus::Cancelled, _) => html! {
            <span class="muted">{ format!("Stopped · {samples} samples") }</span>
        },
        RunState::Finished(s, err) => html! {
            <span class="error">{ format!("{s:?}{}", err.as_ref().map(|e| format!(": {e}")).unwrap_or_default()) }</span>
        },
        RunState::Error(e) => html! { <span class="error">{ e }</span> },
    };
    let csv_href = (!c.signals.is_empty() && !running).then(|| {
        format!(
            "data:text/csv;charset=utf-8,{}",
            String::from(js_sys::encode_uri_component(&c.csv()))
        )
    });
    let o = &*options;
    let validation = o.validate();
    let errors = validation.as_ref().err();
    let number_field = |name: &'static str,
                        title: &'static str,
                        value: &str,
                        field: fn(&mut RunForm) -> &mut String| {
        let error = errors.and_then(|e| e.get(name));
        let error_id = format!("sim-{}-{name}-error", props.file_id);
        html! {
            <label class={classes!("sim-number", error.is_some().then_some("invalid"))}>
                <span>{ title }</span>
                <input type="text" inputmode="decimal" aria-label={title} value={value.to_string()} disabled={running}
                    aria-invalid={error.is_some().to_string()} aria-describedby={error.map(|_| error_id.clone())}
                    oninput={set_num(field)} />
                if let Some(error) = error { <small id={error_id} class="field-error">{ error }</small> }
            </label>
        }
    };
    let progress_value = c.requested_options.as_ref().and_then(|o| {
        c.time.last().map(|time| {
            if o.stop == o.start {
                100.0
            } else {
                ((time - o.start) / (o.stop - o.start) * 100.0).clamp(0.0, 100.0)
            }
        })
    });

    html! {
        <div class="sim-panel">
            <div class="sim-toolbar">
                <div class="sim-heading"><strong>{ "Simulation" }</strong><span class="version-badge">{ format!("Saved v{}", props.version) }</span></div>
                <div class="sim-actions">
                    if running {
                        <button class="stop-button" onclick={cancel} disabled={matches!(&*state, RunState::Stopping)}>{ "■ Stop" }</button>
                    } else {
                        <button class="primary run-button" onclick={run} disabled={validation.is_err()}>{ "▶ Run" }</button>
                    }
                    <span class="sim-status" role="status" aria-live="polite">{ status }</span>
                    if let Some(href) = csv_href {
                        <a class="button" href={href} download="trace.csv">{ "Export CSV" }</a>
                    }
                </div>
            </div>
            <div class="sim-form">
                <div class="sim-primary-options">
                    { number_field("stop", "Stop time (s)", &o.stop, |o| &mut o.stop) }
                    { number_field("step", "Output step (s)", &o.step, |o| &mut o.step) }
                    <label>{ "Solver" }
                        <select onchange={set_solver} disabled={running}>
                            <option value="rk45" selected={o.solver == Solver::Rk45}>{ "RK45 · adaptive" }</option>
                            <option value="rk4" selected={o.solver == Solver::Rk4}>{ "RK4 · fixed step" }</option>
                            <option value="euler" selected={o.solver == Solver::Euler}>{ "Euler · fixed step" }</option>
                        </select>
                    </label>
                    <span class="sample-estimate">
                        { match &validation { Ok((_, n)) => format!("{n} output samples"), Err(_) => "Check run settings".into() } }
                    </span>
                </div>
                <details class="sim-options-details">
                    <summary>{ "Solver settings & workspace" }
                        if let Some(errors) = errors {
                            if errors.keys().any(|key| matches!(*key, "start" | "rtol" | "atol")) {
                                <span class="field-error">{ " · settings need attention" }</span>
                            }
                        }
                    </summary>
                    <div class="sim-advanced-options">
                        { number_field("start", "Start time (s)", &o.start, |o| &mut o.start) }
                        if o.solver == Solver::Rk45 {
                            { number_field("rtol", "Relative tolerance", &o.relative_tolerance, |o| &mut o.relative_tolerance) }
                            { number_field("atol", "Absolute tolerance", &o.absolute_tolerance, |o| &mut o.absolute_tolerance) }
                        }
                        <label title="Runs the pinned version of a project .m script to initialize numeric workspace variables.">{ "Initialization script" }{ init_picker }</label>
                        <label class="grow">{ "Workspace overrides" }
                            <textarea rows="3" value={(*workspace).clone()} oninput={set_workspace} disabled={running} placeholder={"K = 2\nw = 2*pi*5"} />
                            <small>{ "One NAME = expression per line. Overrides take precedence over the script." }</small>
                        </label>
                    </div>
                    <button class="reset-run-settings" onclick={reset_options} disabled={running}>{ "Reset run settings" }</button>
                </details>
                if !props.inputs.is_empty() {
                    <fieldset class="sim-inputs">
                        <legend>{ "Root inputs (constant throughout the run)" }</legend>
                        <p>{ "Enter a numeric expression for each input. Workspace variables are available; values are never filled automatically." }</p>
                        { for props.inputs.iter().map(|(id, name)| {
                            let (inputs, id) = (inputs.clone(), id.clone());
                            let value = inputs.get(&id).cloned().unwrap_or_default();
                            let oninput = Callback::from(move |e: InputEvent| {
                                let mut values = (*inputs).clone();
                                values.insert(id.clone(), e.target_unchecked_into::<HtmlInputElement>().value());
                                inputs.set(values);
                            });
                            html! { <label>{ name }<input type="text" {value} {oninput} placeholder="Required constant expression" disabled={running} /></label> }
                        }) }
                    </fieldset>
                }
            </div>
            if !differences.is_empty() || props.has_random_sources {
                <details class="sim-assumptions">
                    <summary>{ "Model compatibility & run defaults" }</summary>
                    if props.has_random_sources {
                        <p>{ "Random sources are reproducible in Unlinked, but use a different random sequence from Simulink." }</p>
                    }
                    if !differences.is_empty() {
                        <p>{ "Review these defaults: the simulator substituted settings that are missing, invalid, or unsupported in the saved model." }</p>
                        <ul>{ for differences.iter().map(|d| html! { <li>{ d }</li> }) }</ul>
                    }
                </details>
            }
            if running || samples > 0 {
                <div class="sim-progress">
                    if running { <progress max="100" value={progress_value.map(|v| v.to_string())} aria-label="Simulation progress" /> }
                    if let Some(time) = c.time.last() { <span>{ format!("t = {} s · {samples} samples", fmt_num(*time)) }</span> }
                    if running { <span>{ progress_value.map(|v| format!("{v:.0}%")).unwrap_or_else(|| "Preparing model…".into()) }</span> }
                </div>
            }
            <div class="sim-body">
                <div class="results-main">
                    if let Some(version) = c.run_version {
                        <div class="results-identity"><strong>{ format!("Results · v{version}") }</strong>
                            if version != props.version { <span>{ format!("Viewing an earlier model version; Run uses v{}.", props.version) }</span> }
                            if let Some(id) = c.run_id { <span title={id.to_string()}>{ format!("Run {}", &id.to_string()[..8]) }</span> }
                        </div>
                    }
                <div class="plot-host" ref={plot_host}>
                    <canvas id={canvas_id.clone()} hidden={c.signals.is_empty()} />
                    if c.signals.is_empty() {
                        <div class="sim-empty">
                            <span class="sim-empty-icon" aria-hidden="true">{ "∿" }</span>
                            <h3>{ if running { "Preparing simulation" } else if matches!(&*state, RunState::Loading) { "Loading results" } else { "Inspect your model’s response" } }</h3>
                            <p>{ "Run the saved model or open a previous run to plot its signals." }</p>
                            <p class="muted">{ "Choose signals from the list. Scroll to zoom and drag to pan the plot." }</p>
                        </div>
                    }
                </div>
                    if samples > 0 { <Measurements key={c.generation.to_string()} controller={ctl.clone()} samples={samples} selected={c.plotted.clone()} /> }
                </div>
                <aside class="signal-list">
                    <h4>{ format!("Signals · {} selected", c.plotted.len()) }</h4>
                    <input class="signal-search" type="search" aria-label="Search signals" placeholder="Search signals…" value={(*signal_query).clone()} oninput={set_signal_query} />
                    <div class="signal-selection-actions">
                        <button onclick={select_visible(true)} disabled={visible_signals.is_empty()}>{ "Select visible" }</button>
                        <button onclick={select_visible(false)} disabled={visible_signals.is_empty()}>{ "Clear visible" }</button>
                    </div>
                    if matching_signals.len() > visible_signals.len() { <p class="muted signal-count">{ format!("Showing {} of {} matches. Refine search to find more.", visible_signals.len(), matching_signals.len()) }</p> }
                    <div class="signal-options">
                    if visible_signals.is_empty() { <p class="muted">{ if c.signals.is_empty() { "Signals appear after a run starts." } else { "No matching signals." } }</p> }
                    { for visible_signals.iter().copied().map(|i| {
                        let s = &c.signals[i];
                        html! {
                            <label class={classes!("signal", is_generated(s).then_some("generated"))} title={format!("{} ({})", s.name, s.id)}>
                                <input type="checkbox" checked={plotted.contains(&i)} onchange={toggle_signal(i)} />
                                <span class="signal-swatch" style={format!("background:{}", inspector::color(i))} />
                                <span class="signal-name">{ label(&s.name) }</span>
                            </label>
                        }
                    }) }
                    </div>
                    if generated_count > 0 {
                        <label class="signal toggle">
                            <input type="checkbox" checked={*show_generated} onchange={toggle_generated} />
                            { format!("Show {generated_count} generated signals") }
                        </label>
                    }
                    <h4>{ "Previous runs" }</h4>
                    <label class="signal toggle"><input type="checkbox" checked={*current_version_only} onchange={toggle_version_filter} />{ format!("Only v{}", props.version) }</label>
                    { view(&runs, |rs: &Vec<SimulationRun>| html! {
                        <ul class="plain runs">
                            if !rs.iter().any(|r| !*current_version_only || r.file_version == props.version) { <li class="muted">{ "No matching previous runs." }</li> }
                            { for rs.iter().filter(|r| !*current_version_only || r.file_version == props.version).map(|r| html! {
                                <li>
                                    <button class={classes!("run-history-item", (c.run_id == Some(r.id)).then_some("active"))} disabled={running} onclick={load_run(r.clone())} aria-label={format!("Load v{} {:?} run from {} ({})", r.file_version, r.status, r.created_at.format("%Y-%m-%d %H:%M:%S UTC"), &r.id.to_string()[..8])} aria-pressed={(c.run_id == Some(r.id)).to_string()}>
                                        { format!("v{} · {:?}", r.file_version, r.status) }
                                    </button>
                                    <div class="muted">{ r.created_at.format("%Y-%m-%d %H:%M:%S").to_string() }</div>
                                </li>
                            }) }
                        </ul>
                    }) }
                </aside>
            </div>
        </div>
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn config(entries: &[(&str, &str)]) -> SimConfig {
        let raw: BTreeMap<String, String> = entries
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect();
        SimConfig {
            solver: raw.get("Solver").cloned(),
            start_time: raw.get("StartTime").cloned(),
            stop_time: raw.get("StopTime").cloned(),
            fixed_step: raw.get("FixedStep").cloned(),
            raw,
        }
    }

    #[test]
    fn run_options_follow_valid_model_settings_silently() {
        let (o, notes) = initial_options(&config(&[
            ("Solver", "ode4"),
            ("StartTime", "1"),
            ("StopTime", "3"),
            ("FixedStep", "0.5"),
        ]));
        assert_eq!(
            (o.solver, o.start, o.stop, o.step),
            (Solver::Rk4, 1.0, 3.0, 0.5)
        );
        assert!(notes.is_empty(), "{notes:?}");
        let (o, notes) = initial_options(&config(&[
            ("Solver", "ode45"),
            ("StartTime", "0"),
            ("StopTime", "2"),
            ("RelTol", "1e-3"),
            ("AbsTol", "1e-5"),
        ]));
        assert_eq!(o.solver, Solver::Rk45);
        assert_eq!((o.relative_tolerance, o.absolute_tolerance), (1e-3, 1e-5));
        assert!(notes.is_empty(), "{notes:?}");
    }

    #[test]
    fn every_substituted_run_option_is_listed() {
        let (o, notes) = initial_options(&config(&[
            ("Solver", "ode15s"),
            ("StartTime", "0"),
            ("StopTime", "-1"),
            ("RelTol", "auto"),
        ]));
        assert_eq!((o.solver, o.stop), (Solver::Rk45, 10.0));
        for about in ["Solver", "Stop", "Rel tol", "Abs tol"] {
            assert!(
                notes.iter().any(|n| n.starts_with(about)),
                "{about}: {notes:?}"
            );
        }
        let (o, notes) = initial_options(&config(&[
            ("Solver", "ode1"),
            ("StartTime", "Tstart"),
            ("StopTime", "1"),
            ("FixedStep", "0"),
        ]));
        assert_eq!((o.solver, o.start, o.step), (Solver::Euler, 0.0, 1e-3));
        assert!(notes.iter().any(|n| n.starts_with("Start")), "{notes:?}");
        assert!(
            notes.iter().any(|n| n.starts_with("Output step")),
            "{notes:?}"
        );
    }

    fn sig(id: &str, name: &str) -> SimulationSignal {
        SimulationSignal {
            id: id.into(),
            name: format!("m/{name}"),
        }
    }

    fn signals() -> Vec<SimulationSignal> {
        vec![
            sig("1[1]", "Sum[1]:1"),
            sig("3[1]:$gain:1", "A[1]/term1:1"),
            sig("2", "Gain:1"),
            sig("7", "cart position (m):1"),
        ]
    }

    #[test]
    fn picker_lists_outports_first_and_hides_generated() {
        let outports = vec!["cart position (m)".to_string()];
        assert_eq!(picker_order(&signals(), &outports, false), vec![3, 0, 2]);
        assert_eq!(picker_order(&signals(), &outports, true), vec![3, 0, 2, 1]);
    }

    #[test]
    fn stored_columns_follow_recorded_order_and_names() {
        let columns = BTreeMap::from([
            ("10".to_string(), vec![1.0]),
            ("7".to_string(), vec![2.0]),
            ("9".to_string(), vec![3.0]),
        ]);
        let recorded = vec![sig("7", "cart position (m):1"), sig("10", "force:1")];
        let (signals, data) = stored_columns(columns, &recorded);
        let ids: Vec<&str> = signals.iter().map(|s| s.id.as_str()).collect();
        assert_eq!(ids, ["7", "10", "9"]);
        assert_eq!(label(&signals[0].name), "cart position (m):1");
        // No metadata for "9": labelled by its ID.
        assert_eq!(signals[2].name, "9");
        assert_eq!(data, vec![vec![2.0], vec![1.0], vec![3.0]]);
    }

    #[test]
    fn defaults_prefer_outports_then_block_outputs() {
        let outports = vec!["cart position (m)".to_string()];
        assert_eq!(default_plotted(&signals(), &outports), vec![3]);
        assert_eq!(default_plotted(&signals(), &[]), vec![0, 2, 3]);
    }
}
